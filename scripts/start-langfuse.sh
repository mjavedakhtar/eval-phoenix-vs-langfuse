#!/usr/bin/env bash
# Clone the official Langfuse stack (once) and start it locally.
# UI default: http://localhost:3000  — if that port is busy, binds 3001.
# Creates a local project on first boot so you do not need cloud signup.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/.local/langfuse"
HOST_PORT=3000

if ! command -v docker >/dev/null 2>&1; then
  echo "Docker is required to self-host Langfuse." >&2
  exit 1
fi

if lsof -nP -iTCP:3000 -sTCP:LISTEN >/dev/null 2>&1; then
  HOST_PORT=3001
  echo "Port 3000 is in use; Langfuse UI will be http://localhost:${HOST_PORT}"
fi

if [[ ! -d "$DEST/.git" ]]; then
  mkdir -p "$ROOT/.local"
  git clone --depth=1 https://github.com/langfuse/langfuse.git "$DEST"
fi

COMPOSE_ENV="$DEST/.env"
if [[ ! -f "$COMPOSE_ENV" ]]; then
  PK="pk-lf-$(openssl rand -hex 16)"
  SK="sk-lf-$(openssl rand -hex 16)"
  cat >"$COMPOSE_ENV" <<EOF
NEXTAUTH_URL=http://localhost:${HOST_PORT}
LANGFUSE_INIT_ORG_ID=lab
LANGFUSE_INIT_ORG_NAME=lab
LANGFUSE_INIT_PROJECT_ID=data-fabric-agent
LANGFUSE_INIT_PROJECT_NAME=data-fabric-agent
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=${PK}
LANGFUSE_INIT_PROJECT_SECRET_KEY=${SK}
LANGFUSE_INIT_USER_EMAIL=lab@example.com
LANGFUSE_INIT_USER_NAME=lab
LANGFUSE_INIT_USER_PASSWORD=lab-local-only
EOF
  echo "Wrote first-boot keys to ${COMPOSE_ENV}"
else
  # Keep NEXTAUTH_URL aligned with the port we actually bind.
  if grep -q '^NEXTAUTH_URL=' "$COMPOSE_ENV"; then
    sed -i.bak "s|^NEXTAUTH_URL=.*|NEXTAUTH_URL=http://localhost:${HOST_PORT}|" "$COMPOSE_ENV"
    rm -f "$COMPOSE_ENV.bak"
  else
    echo "NEXTAUTH_URL=http://localhost:${HOST_PORT}" >>"$COMPOSE_ENV"
  fi
fi

# Official Compose is a production stack (unbounded ClickHouse threads, worker
# concurrency 20, telemetry query_log scans). Cap it for a 4-CPU Colima VM.
# Also disable v4 legacy-API usage jobs — those are what hung Tracing.
if ! grep -q '^TELEMETRY_ENABLED=' "$COMPOSE_ENV"; then
  echo "TELEMETRY_ENABLED=false" >>"$COMPOSE_ENV"
else
  sed -i.bak "s|^TELEMETRY_ENABLED=.*|TELEMETRY_ENABLED=false|" "$COMPOSE_ENV"
  rm -f "$COMPOSE_ENV.bak"
fi

cat >"$DEST/docker-compose.override.yml" <<EOF
# Generated by scripts/start-langfuse.sh — laptop lab limits, not production.
x-lab-env: &lab-env
  TELEMETRY_ENABLED: "false"
  LANGFUSE_ENABLE_EXPERIMENTAL_FEATURES: "false"
  NODE_OPTIONS: "--max-old-space-size=1536"
  LANGFUSE_INGESTION_QUEUE_PROCESSING_CONCURRENCY: "1"
  LANGFUSE_INGESTION_SECONDARY_QUEUE_PROCESSING_CONCURRENCY: "1"
  LANGFUSE_OTEL_INGESTION_QUEUE_PROCESSING_CONCURRENCY: "1"
  LANGFUSE_TRACE_UPSERT_WORKER_CONCURRENCY: "1"
  LANGFUSE_EVAL_EXECUTION_WORKER_CONCURRENCY: "1"
  QUEUE_CONSUMER_V4_LEGACY_API_USAGE_QUEUE_IS_ENABLED: "false"
  QUEUE_CONSUMER_CLOUD_USAGE_METERING_QUEUE_IS_ENABLED: "false"
  QUEUE_CONSUMER_CLOUD_SPEND_ALERT_QUEUE_IS_ENABLED: "false"
  QUEUE_CONSUMER_FREE_TIER_USAGE_THRESHOLD_QUEUE_IS_ENABLED: "false"
  QUEUE_CONSUMER_POSTHOG_INTEGRATION_QUEUE_IS_ENABLED: "false"
  QUEUE_CONSUMER_MIXPANEL_INTEGRATION_QUEUE_IS_ENABLED: "false"
  QUEUE_CONSUMER_BLOB_STORAGE_INTEGRATION_QUEUE_IS_ENABLED: "false"
  QUEUE_CONSUMER_BATCH_EXPORT_QUEUE_IS_ENABLED: "false"
  QUEUE_CONSUMER_CODE_EVAL_EXECUTION_QUEUE_IS_ENABLED: "false"

services:
  langfuse-web:
    platform: linux/arm64
    ports: !override
      - "${HOST_PORT}:3000"
    cpus: 0.75
    mem_limit: 2g
    environment:
      <<: *lab-env
  langfuse-worker:
    platform: linux/arm64
    cpus: 0.5
    mem_limit: 512m
    environment:
      <<: *lab-env
  clickhouse:
    platform: linux/arm64
    cpus: 2.0
    mem_limit: 2g
    healthcheck:
      interval: 10s
      timeout: 5s
      retries: 30
      start_period: 180s
  postgres:
    platform: linux/arm64
    cpus: 0.4
    mem_limit: 256m
    command: postgres -c shared_buffers=128MB -c max_connections=50 -c work_mem=4MB
    healthcheck:
      interval: 15s
      timeout: 30s
      retries: 10
      start_period: 20s
  minio:
    platform: linux/arm64
    cpus: 0.4
    mem_limit: 256m
    healthcheck:
      interval: 15s
      timeout: 30s
      retries: 10
      start_period: 20s
  redis:
    platform: linux/arm64
    cpus: 0.2
    mem_limit: 128m
    command: >
      --requirepass \${REDIS_AUTH:-myredissecret}
      --maxmemory 64mb
      --maxmemory-policy noeviction
EOF

# Mirror keys into the lab .env (gitignored).
PK="$(awk -F= '/^LANGFUSE_INIT_PROJECT_PUBLIC_KEY=/{print $2}' "$COMPOSE_ENV")"
SK="$(awk -F= '/^LANGFUSE_INIT_PROJECT_SECRET_KEY=/{print $2}' "$COMPOSE_ENV")"
LAB_ENV="$ROOT/.env"
touch "$LAB_ENV"
python3 - "$LAB_ENV" "$HOST_PORT" "$PK" "$SK" <<'PY'
from pathlib import Path
import sys
path, port, pk, sk = Path(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4]
text = path.read_text() if path.exists() else ""
replacements = {
    "LANGFUSE_BASE_URL": f"http://localhost:{port}",
    "LANGFUSE_HOST": f"http://localhost:{port}",
    "LANGFUSE_PUBLIC_KEY": pk,
    "LANGFUSE_SECRET_KEY": sk,
}
lines = text.splitlines() if text else []
seen = set()
out = []
for line in lines:
    key = line.split("=", 1)[0] if "=" in line and not line.strip().startswith("#") else None
    if key in replacements:
        out.append(f"{key}={replacements[key]}")
        seen.add(key)
    else:
        out.append(line)
for key, value in replacements.items():
    if key not in seen:
        out.append(f"{key}={value}")
path.write_text("\n".join(out) + "\n")
PY

cd "$DEST"
if docker compose version >/dev/null 2>&1; then
  docker compose up -d --force-recreate
else
  docker-compose up -d --force-recreate
fi
echo
echo "Langfuse is starting (lab CPU caps applied). Open http://localhost:${HOST_PORT}"
echo "Local login: lab@example.com / lab-local-only  (this machine only)"
echo "Then: uv run python experiments/run_langfuse.py"
